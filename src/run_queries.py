"""
Stage 3b: run every named query in sql/queries.sql.

Output  outputs/query_results/<name>.csv
        docs/sql_results.md   (question, SQL and first rows of each result)
"""
from __future__ import annotations

import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs" / "query_results"


def parse_queries(text: str) -> list[tuple[str, str, str]]:
    blocks = re.split(r"^-- name:\s*", text, flags=re.M)[1:]
    out = []
    for b in blocks:
        name, body = b.split("\n", 1)
        comments = [l[3:] for l in body.splitlines() if l.startswith("-- ")]
        sql = "\n".join(l for l in body.splitlines() if not l.startswith("--")).strip()
        out.append((name.strip(), " ".join(comments), sql))
    return out


def main():
    con = sqlite3.connect(ROOT / "autovoice.db")
    OUT.mkdir(parents=True, exist_ok=True)
    md = ["# SQL results", "", "_Auto-generated by `src/run_queries.py` from `sql/queries.sql`. "
          "**Synthetic data: numbers illustrate the method, not a real market.**_", ""]
    for name, question, sql in parse_queries((ROOT / "sql" / "queries.sql").read_text()):
        res = pd.read_sql_query(sql, con)
        res.to_csv(OUT / f"{name}.csv", index=False)
        md += [f"## {name}", "", question, "", "```sql", sql, "```", "",
               res.head(12).to_markdown(index=False), ""]
        if len(res) > 12:
            md += [f"_{len(res) - 12} more rows in `outputs/query_results/{name}.csv`_", ""]
        print(f"{name:<36} {len(res):>4} rows")
    (ROOT / "docs" / "sql_results.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
